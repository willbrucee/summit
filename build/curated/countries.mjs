export function parseCountries() {
  return COUNTRIES.trim().split('\n').map((line) => {
    const [name, tags = '', ...caps] = line.split(';').map((s) => s.trim());
    const [label, ...aliases] = name.split('|').map((s) => s.trim());
    const capitals = caps.filter(Boolean).map((c) => {
      const [cl, ...ca] = c.split('|').map((s) => s.trim());
      return { label: cl, aliases: ca };
    });
    return { label, aliases, tags: tags.split(/\s+/).filter(Boolean), capitals };
  });
}
